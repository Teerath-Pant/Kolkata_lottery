import { sql } from 'drizzle-orm';
import {
  type AnyPgColumn, bigint, boolean, check, index, integer, jsonb, pgEnum, pgTable, primaryKey, serial, text, timestamp, uniqueIndex,
} from 'drizzle-orm/pg-core';

export const roleEnum = pgEnum('role', ['user', 'admin']);
export const ledgerTypeEnum = pgEnum('ledger_type', [
  'signup_bonus', 'daily_claim', 'ticket_purchase', 'prize', 'refund', 'admin_adjust',
]);
export const prizeTypeEnum = pgEnum('prize_type', ['fixed', 'pool_percent']);
export const themeEnum = pgEnum('theme', [
  'green', 'red', 'blue', 'purple', 'pink', 'orange', 'yellow', 'teal', 'cyan', 'indigo', 'maroon', 'brown', 'black',
]);
export const drawStatusEnum = pgEnum('draw_status', ['open', 'drawing', 'completed', 'cancelled']);
export const drawModeEnum = pgEnum('draw_mode', ['random', 'admin_selected']);
export const complaintStatusEnum = pgEnum('complaint_status', ['open', 'resolved']);

const ts = (name: string) => timestamp(name, { withTimezone: true });
const big = (name: string) => bigint(name, { mode: 'number' });

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  username: text('mobile').notNull().unique(),
  name: text('name').notNull(),
  phone: text('phone').unique(), // verified mobile number (OTP at signup); null for accounts created before OTP existed
  passwordHash: text('password_hash').notNull(),
  role: roleEnum('role').notNull().default('user'),
  createdAt: ts('created_at').notNull().defaultNow(),
  // shareable code (link /login?ref=CODE); generated by the database so every row, old or new, gets one
  referralCode: text('referral_code').notNull().unique()
    .default(sql`upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8))`),
  referredBy: integer('referred_by').references((): AnyPgColumn => users.id), // null only for the root (admin)
}, (t) => [index('users_referred_by_idx').on(t.referredBy)]);

// Referral tree as a closure table: one row per (ancestor, descendant) pair, depth 1 = direct referral.
// Lets any level of anyone's downline / upline be read with one query. Stored only, never shown in the UI.
export const referralTree = pgTable('referral_tree', {
  ancestorId: integer('ancestor_id').notNull().references(() => users.id),
  descendantId: integer('descendant_id').notNull().references(() => users.id),
  depth: integer('depth').notNull(),
}, (t) => [
  primaryKey({ columns: [t.ancestorId, t.descendantId] }),
  index('referral_tree_descendant_idx').on(t.descendantId),
  check('referral_tree_depth_pos', sql`${t.depth} >= 1`),
]);

export const wallets = pgTable('wallets', {
  userId: integer('user_id').primaryKey().references(() => users.id),
  balance: big('balance').notNull().default(0),
  updatedAt: ts('updated_at').notNull().defaultNow(),
}, (t) => [check('wallet_balance_nonneg', sql`${t.balance} >= 0`)]);

export const walletLedger = pgTable('wallet_ledger', {
  id: serial('id').primaryKey(),
  userId: integer('user_id').notNull().references(() => users.id),
  amount: big('amount').notNull(),
  type: ledgerTypeEnum('type').notNull(),
  refId: integer('ref_id'),
  balanceAfter: big('balance_after').notNull(),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [
  index('ledger_user_created_idx').on(t.userId, t.createdAt),
  // prize / refund can only be paid once per user per draw (belt and braces for job idempotency)
  uniqueIndex('ledger_pay_once_idx').on(t.userId, t.refId, t.type).where(sql`type IN ('prize','refund')`),
]);

export const packages = pgTable('packages', {
  id: serial('id').primaryKey(),
  name: text('name').notNull(),
  price: big('price').notNull(),
  prizeType: prizeTypeEnum('prize_type').notNull(),
  prizeValue: big('prize_value').notNull(),
  maxTickets: integer('max_tickets').notNull(),
  // schedule: EITHER repeat every N minutes OR once a day at daily_time ("HH:MM", Indian Standard Time)
  drawIntervalMinutes: integer('draw_interval_minutes'),
  dailyTime: text('daily_time'),
  theme: themeEnum('theme').notNull(),
  isActive: boolean('is_active').notNull().default(true),
  // soft delete: the row stays so past draws, results and the audit log keep their package
  deletedAt: ts('deleted_at'),
}, (t) => [
  check('pkg_price_pos', sql`${t.price} > 0`),
  check('pkg_max_range', sql`${t.maxTickets} BETWEEN 1 AND 9999`),
  check('pkg_interval_pos', sql`${t.drawIntervalMinutes} IS NULL OR ${t.drawIntervalMinutes} > 0`),
  check('pkg_daily_time_fmt', sql`${t.dailyTime} IS NULL OR ${t.dailyTime} ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'`),
  check('pkg_one_schedule', sql`(${t.drawIntervalMinutes} IS NULL) <> (${t.dailyTime} IS NULL)`),
]);

// Consolation prizes by leading-digit match with the winning ticket (1..5 digits; 6 = the main prize).
// Admin-editable defaults per package; copied onto each draw at open time (draw_tier_prizes).
export const packageTierPrizes = pgTable('package_tier_prizes', {
  packageId: integer('package_id').notNull().references(() => packages.id),
  matchDigits: integer('match_digits').notNull(),
  prize: big('prize').notNull().default(0),
}, (t) => [
  primaryKey({ columns: [t.packageId, t.matchDigits] }),
  check('pkg_tier_digits_range', sql`${t.matchDigits} BETWEEN 1 AND 5`),
  check('pkg_tier_prize_nonneg', sql`${t.prize} >= 0`),
]);

// Package values are snapshotted onto each draw at open time, so editing a package never
// changes the rules of a draw people already bought into.
export const draws = pgTable('draws', {
  id: serial('id').primaryKey(),
  packageId: integer('package_id').notNull().references(() => packages.id),
  drawTime: ts('draw_time').notNull(),
  status: drawStatusEnum('status').notNull().default('open'),
  mode: drawModeEnum('mode').notNull().default('random'),
  selectedTicketNo: integer('selected_ticket_no'),
  winningTicketNo: integer('winning_ticket_no'),
  winnerUserId: integer('winner_user_id').references(() => users.id),
  prizeAmount: big('prize_amount'),
  winMethod: text('win_method'), // random | admin_selected | fallback_random
  ticketPrice: big('ticket_price').notNull(),
  prizeType: prizeTypeEnum('prize_type').notNull(),
  prizeValue: big('prize_value').notNull(),
  maxTickets: integer('max_tickets').notNull(),
  serverSeedHash: text('server_seed_hash').notNull(),
  serverSeed: text('server_seed'), // null until reveal
  createdAt: ts('created_at').notNull().defaultNow(),
  completedAt: ts('completed_at'),
}, (t) => [
  index('draws_pkg_status_idx').on(t.packageId, t.status),
  index('draws_status_time_idx').on(t.status, t.drawTime),
  uniqueIndex('one_open_draw_per_package').on(t.packageId).where(sql`status = 'open'`),
]);

export const drawTierPrizes = pgTable('draw_tier_prizes', {
  drawId: integer('draw_id').notNull().references(() => draws.id),
  matchDigits: integer('match_digits').notNull(),
  prize: big('prize').notNull().default(0),
}, (t) => [
  primaryKey({ columns: [t.drawId, t.matchDigits] }),
  check('draw_tier_digits_range', sql`${t.matchDigits} BETWEEN 1 AND 5`),
  check('draw_tier_prize_nonneg', sql`${t.prize} >= 0`),
]);

export const tickets = pgTable('tickets', {
  id: serial('id').primaryKey(),
  drawId: integer('draw_id').notNull().references(() => draws.id),
  userId: integer('user_id').notNull().references(() => users.id),
  ticketNo: integer('ticket_no').notNull(),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [
  uniqueIndex('tickets_draw_no_uq').on(t.drawId, t.ticketNo),
  index('tickets_draw_user_idx').on(t.drawId, t.userId),
  index('tickets_user_idx').on(t.userId),
]);

// One row per ticket that won a leading-digit consolation prize (the main winner is on draws).
export const drawTierWinners = pgTable('draw_tier_winners', {
  id: serial('id').primaryKey(),
  drawId: integer('draw_id').notNull().references(() => draws.id),
  userId: integer('user_id').notNull().references(() => users.id),
  ticketNo: integer('ticket_no').notNull(),
  matchDigits: integer('match_digits').notNull(),
  prize: big('prize').notNull(),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [
  uniqueIndex('tier_winner_once_idx').on(t.drawId, t.ticketNo),
  index('tier_winner_draw_idx').on(t.drawId),
  check('tier_winner_digits_range', sql`${t.matchDigits} BETWEEN 1 AND 5`),
]);

export const adminAuditLog = pgTable('admin_audit_log', {
  id: serial('id').primaryKey(),
  adminId: integer('admin_id').references(() => users.id), // null = system action
  action: text('action').notNull(),
  drawId: integer('draw_id').references(() => draws.id),
  payload: jsonb('payload'),
  ip: text('ip'),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [index('audit_created_idx').on(t.createdAt)]);

// Problems / complaints players send from the Help page; admins read and resolve them in the admin panel.
export const complaints = pgTable('complaints', {
  id: serial('id').primaryKey(),
  userId: integer('user_id').notNull().references(() => users.id),
  subject: text('subject').notNull(),
  message: text('message').notNull(),
  status: complaintStatusEnum('status').notNull().default('open'),
  createdAt: ts('created_at').notNull().defaultNow(),
  resolvedAt: ts('resolved_at'),
}, (t) => [
  index('complaints_user_created_idx').on(t.userId, t.createdAt),
  index('complaints_status_idx').on(t.status, t.createdAt),
]);

// Refresh tokens are single-use: each refresh revokes the presented token and issues the next one in the same
// family. Presenting an already-used token (theft signal) revokes the whole family. Logout revokes the family.
export const refreshTokens = pgTable('refresh_tokens', {
  jti: text('jti').primaryKey(),
  familyId: text('family_id').notNull(),
  userId: integer('user_id').notNull().references(() => users.id),
  expiresAt: ts('expires_at').notNull(),
  revokedAt: ts('revoked_at'), // set on rotation, logout and family revocation
  rotatedAt: ts('rotated_at'), // set only when exchanged for a new token (allows the short race grace)
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [index('refresh_family_idx').on(t.familyId), index('refresh_expires_idx').on(t.expiresAt)]);

// Failed-login counter per user ID (also for IDs that do not exist, so lockouts do not reveal which accounts exist).
export const loginThrottle = pgTable('login_throttle', {
  username: text('username').primaryKey(),
  failures: integer('failures').notNull().default(0),
  windowStart: ts('window_start').notNull().defaultNow(),
  lockedUntil: ts('locked_until'),
});

// One live OTP per mobile number: only a hash is stored, and it dies after OTP_TTL_MINUTES or OTP_MAX_ATTEMPTS wrong tries.
export const otpCodes = pgTable('otp_codes', {
  mobile: text('mobile').primaryKey(),
  codeHash: text('code_hash').notNull(),
  expiresAt: ts('expires_at').notNull(),
  attempts: integer('attempts').notNull().default(0),
  lastSentAt: ts('last_sent_at').notNull(),
  sendWindowStart: ts('send_window_start').notNull(),
  sends: integer('sends').notNull().default(1),
});

export const idempotencyKeys = pgTable('idempotency_keys', {
  key: text('key').notNull(),
  requestHash: text('request_hash'), // binds the key to one request (draw + choice); null on rows from before this existed
  userId: integer('user_id').notNull().references(() => users.id),
  response: jsonb('response').notNull(),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [primaryKey({ columns: [t.userId, t.key] })]);
